import { readFile } from 'node:fs/promises';
import { strict as assert } from 'node:assert';
import { test } from 'node:test';

const plugin = new URL('../plugin-perception/', import.meta.url);
const read = path => readFile(new URL(path, plugin), 'utf8');

test('native voice receipt commands agree across Rust, Swift and Tauri permissions', async () => {
  const [build, rust, swift, permissions, capability] = await Promise.all([
    read('build.rs'), read('src/lib.rs'), read('ios/Sources/PerceptionPlugin.swift'), read('permissions/default.toml'),
    readFile(new URL('../src-tauri/capabilities/device.json', import.meta.url), 'utf8'),
  ]);
  assert.ok(JSON.parse(capability).permissions.includes('perception:default'));
  const commands = [
    ['list_voice_receipts', 'listVoiceReceipts'], ['get_voice_receipt', 'getVoiceReceipt'],
    ['discard_voice_receipt', 'discardVoiceReceipt'], ['release_retained_voice', 'releaseRetainedVoice'],
  ];
  for (const [command, native] of commands) {
    assert.ok(build.includes(`"${command}"`), `${command} missing from plugin build`);
    assert.match(rust, new RegExp(`async fn ${command}\\b`));
    assert.match(rust, new RegExp(`native_call\\(app, "${native}"`));
    assert.match(rust, new RegExp(`\\b${command},`));
    assert.match(swift, new RegExp(`@objc func ${native}\\(`));
    assert.ok(permissions.includes(`"allow-${command.replaceAll('_', '-')}"`));
    const generated = await read(`permissions/autogenerated/commands/${command}.toml`);
    assert.ok(generated.includes(`commands.allow = ["${command}"]`));
  }
});
